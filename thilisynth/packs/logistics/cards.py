    lines = [
        "# Corpus Card — `invoices-v1`",
        "",
        f"> {st['invoices']} carrier invoices for {st['loads']} loads from `tenders-v1`, generated by thilisynth from seed `{seed}`.",
        "",
        "## Reproduce",
        "",
        "```",
        f"seed          {seed}",
        f"loads         {st['loads']}   (the first {st['loads']} tenders of tenders-v1)",
        f"dialects      {len(DIALECTS)}",
        "```",
        "",
        "Same seed, same invoices.",
        "",
        "## Provenance",
        "",
        "| Layer | Origin |",
        "|---|---|",
        "| Load, carrier, rates | The tender; a carrier from `carriers-v1` that serves the lane; the rate card's fuel and accessorial schedule |",
        "| Rate confirmation | The carrier's ask for the lane, less four percent, to the $25 and never below its floor |",
        "| Gate log | Sampled in code. The delivery date is the one on the load's Proof of Delivery in `docs-v1` |",
        "| Invoice | Built from the facts, in the carrier's own wording, then overcharged in code. **No model writes anything** |",
        "| Overcharge labels and amounts | Planted in code, so each is true by construction and the amount is known to the cent |",
        "",
        "## What an invoice is",
        "",
        "A number, a date and a list of lines (a description in the carrier's wording, a quantity, a unit price and an amount). It is "
        "structured data, **not a scan**: reading a page is a different drill's subject.",
        "",
        "## Planted overcharges",
        "",
        "| Class | Configured rate (loads) | Loads carrying it | Evidence a person can check |",
        "|---|---|---|---|",
    ]
    for cls, rate in AUDIT_DEFECTS.items():
        lines.append(f"| `{cls}` | {rate:.2f} | {st['planted_defects'].get(cls, 0)} | `{EVIDENCE_SOURCE[cls]}` |")
    lines += [
        "",
        f"Overbilled: **${st['overbilled_usd']:,.2f}** of ${st['billed_usd']:,.2f} billed ({st['overbilled_share']:.1%}). "
        f"{st['dispute_share']:.1%} of invoices carry at least one overcharge.",
        "",
        "| Class | Lines | Dollars overbilled |",
        "|---|---|---|",
    ]
    for cls in AUDIT_DEFECTS:
        lines.append(f"| `{cls}` | {st['lines_by_class'].get(cls, 0)} | ${st['overbilled_by_class'].get(cls, 0.0):,.2f} |")
    lines += [
        "",
        "## Things that look odd and are right",
        "",
        f"- **Detention the gate log supports:** {st['legit_detention_lines']} invoice lines. Billing it is not an overcharge.",
        "- **Four dialects:** the same charge worded four ways (`Detention`, `DTN HRS`, `Waiting Time`, `ACC-DET Det. time`). "
        f"Invoices per dialect: {st['dialects']}.",
        f"- **Rounding:** one dialect bills whole dollars. The largest gap between what is billed and what is owed, once the planted "
        f"overcharges are set aside, is ${st['max_rounding_usd']:.2f}.",
        "- **Authorised extras** billed at the schedule rate.",
        "",
        "## Failure modes this corpus does NOT contain",
        "",
        "- **Only the overcharges that were planted.** Real carriers over-bill in ways nobody catalogued. A system scored here reports its "
        "recall against the errors that were planted, and recovery measured here is an **optimistic bound**.",
        "- **Whether an authorised extra was actually performed.** The data cannot tell, so an authorised charge is payable.",
        "- No undercharges, no credits, no claims for damaged freight, no taxes and no currency.",
        "- One invoice per load, plus duplicates. No supplementary or corrected invoices.",
        "- Four dialects only. A fifth carrier will word things in ways these four do not.",
        "- Detention, fuel and accessorial rules are Harborline's, not an industry standard. Carrier, load and company names are synthetic.",
        "",
        "---",
        "",
        "Generated by [thilisynth](https://github.com/thili-ai/thilisynth) for the Learn Fast drill",
        "*Audit the Carrier Invoice*.",
        "",
    ]
    return "\n".join(lines)


