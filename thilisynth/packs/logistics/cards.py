def carriers_card(carriers: Sequence[Carrier], seed: int) -> str:
    base = [c for c in carriers if c.lookalike_of is None]
    observed = observed_traps(carriers)
    lines: List[str] = [
        "# Corpus Card — `carriers-v1`",
        "",
        f"> {len(carriers)} carriers ({len(base)} named in the tenders, {len(carriers) - len(base)} look-alikes), "
        f"generated by thilisynth from seed `{seed}`, as of {AS_OF.isoformat()}.",
        "",
        "## Reproduce",
        "",
        "```",
        f"seed          {seed}",
        f"as_of         {AS_OF.isoformat()}",
        f"carriers      {len(base)} + {len(carriers) - len(base)} look-alikes",
        "```",
        "",
        "Same seed, same carriers.",
        "",
        "## Provenance",
        "",
        "| Layer | Origin |",
        "|---|---|",
        "| Carrier names | The 70 synthetic names in `reference.CARRIERS`, so every tender's `carrier_invited` resolves to a row |",
        "| MC and DOT numbers | Synthetic. Not drawn from FMCSA |",
        "| Authority, insurance, safety, history | Sampled in code from a seed. **Never model-generated.** |",
        "| Trap labels | Planted by code after sampling, so each label is true by construction |",
        "",
        "## Traps present",
        "",
        "| Trap | Configured rate | Carriers carrying it |",
        "|---|---|---|",
    ]
    for trap in sorted(TRAP_RATES):
        lines.append(f"| `{trap}` | {TRAP_RATES[trap]:.2f} (at least {MIN_PER_TRAP}) | {observed.get(trap, 0)} |")
    lines.append(f"| `name_collision` | {N_LOOKALIKES} look-alikes | {observed.get('name_collision', 0)} |")
    never = [t for t in list(TRAP_RATES) + ["name_collision"] if observed.get(t, 0) == 0]
    lines += ["", "## Failure modes this corpus does NOT contain", ""]
    if never:
        lines += ["**Configured but never fired:**", ""] + [f"- `{t}`" for t in never] + [""]
    lines += [
        "- Names, MC numbers and DOT numbers are synthetic; nothing is checked against a real registry.",
        "- No capacity or availability by date: a carrier that serves a lane is assumed able to take the load.",
        "- Lanes are hub-level (20 cities). There is no regional pricing and no seasonality.",
        "- Authority, insurance and safety are one snapshot. The only change over time is the contact-change flag.",
        "- A recent contact change stands in for the double-brokering signals; real ones are richer.",
        "- Rate history is five numbers per carrier near the benchmark.",
        "",
        "---",
        "",
        "Generated by [thilisynth](https://github.com/thili-ai/thilisynth) for the Learn Fast drill",
        "*Build a Carrier Booking Agent*.",
        "",
    ]
    return "\n".join(lines)


def ratecard_card(card: RateCard) -> str:
    lines = [
        "# Corpus Card — `ratecard-v1`",
        "",
        f"> The rates and rules of Harborline's booking desk, as of {card.as_of}.",
        "",
        "## What it holds",
        "",
        "| Item | Value |",
        "|---|---|",
    ]
    for eq, rate in sorted(card.benchmark_per_mile.items()):
        lines.append(f"| Benchmark, {eq} | ${rate:.2f} per mile |")
    lines += [
        f"| Carrier ceiling | {card.carrier_ceiling_multiplier:.2f} x benchmark |",
        f"| Margin floor | {card.margin_floor:.0%} of the sell rate |",
        f"| Desk booking authority | ${card.desk_authority_usd:,} sell value |",
        f"| Fuel surcharge | ${card.fuel_surcharge_per_mile:.2f} per mile (for the billing drill) |",
        f"| Accessorial schedule | {len(card.accessorials_usd)} charges (for the billing drill) |",
        "",
        "## Provenance",
        "",
        "The per-mile benchmarks are the anchors the tenders were built from "
        "(`reference.RATE_PER_MILE`), and the benchmark is computed the same way, with the same "
        "rounding, so a tender's offered rate sits within 0.88 to 1.18 of the card's benchmark.",
        "",
        "## Failure modes this corpus does NOT contain",
        "",
        "- One national anchor per equipment type. No lane, season or fuel-index variation.",
        "- The sell side is the tender's own offered rate. There is no per-shipper contract table.",
        "- The margin floor and the desk authority are Harborline's rules in this course, not industry figures.",
        "- The fuel surcharge and accessorial schedule are not used to price a booking in this drill.",
        "",
        "---",
        "",
        "Generated by [thilisynth](https://github.com/thili-ai/thilisynth) for the Learn Fast drill",
        "*Build a Carrier Booking Agent*.",
        "",
    ]
    return "\n".join(lines)


def truth_card(outcomes: Sequence[Outcome], card: RateCard) -> str:
    s = truth_summary(outcomes)
    lines = [
        "# Corpus Card — booking ground truth for `tenders-v1`",
        "",
        f"> The correct outcome for {s['n']} tenders: book a carrier at a rate, or escalate for a reason.",
        "",
        "## How the truth is derived",
        "",
        "In code, from facts planted in the data: the defect flags on the thread, the carrier master and "
        "the rate card. The rules live in the dataset and are separate from the learner's own policy, so "
        "an agent cannot mark itself right.",
        "",
        "## What it contains",
        "",
        f"- Book: **{s['book_share']:.1%}**. Escalate: **{s['escalate_share']:.1%}**.",
        f"- Threads delivered twice (the booking must still happen once): **{s['duplicate_deliveries']}**.",
        f"- The carrier named on the thread is an acceptable one in **{s['invited_carrier_ok_share']:.1%}** of tenders.",
        "",
        "| Escalation reason | Primary | Present at all |",
        "|---|---|---|",
    ]
    for r in REASON_PRIORITY:
        lines.append(f"| `{r}` | {s['primary_reason_counts'].get(r, 0)} | {s['any_reason_counts'].get(r, 0)} |")
    lines += [
        "",
        "## Failure modes this corpus does NOT contain",
        "",
        "- Every vague pickup escalates, because none of the vague phrases in the corpus names a date. "
        "There are no resolvable relative dates (\"next Tuesday\") in the tenders.",
        "- No oversize loads: tender weights never exceed the trailer limit, so there is no `oversize` reason.",
        "- Hazmat appears only as the footer defect. No other form of hazmat language is present.",
        "- The carrier named on the thread is usually not a fit for the lane, so it carries no signal about the right carrier.",
        "",
        "---",
        "",
        "Generated by [thilisynth](https://github.com/thili-ai/thilisynth) for the Learn Fast drill",
        "*Build a Carrier Booking Agent*.",
        "",
    ]
    return "\n".join(lines)


def docs_card(loads: Sequence[LoadPaperwork], seed: int) -> str:
    st = paperwork_stats(loads)
    n = st["n"]
    lines = [
        "# Corpus Card — `docs-v1`",
        "",
        f"> A Bill of Lading and a Proof of Delivery for each of {n} loads from `tenders-v1`, "
        f"generated by thilisynth from seed `{seed}`.",
        "",
        "## Reproduce",
        "",
        "```",
        f"seed          {seed}",
        f"loads         {n}   (the first {n} tenders of tenders-v1)",
        f"templates     {N_TEMPLATES}",
        "```",
        "",
        "Same seed, same documents.",
        "",
        "## Provenance",
        "",
        "| Layer | Origin |",
        "|---|---|",
        "| Load facts | The tender record: load id, shipper, cities, pieces, weight, commodity, HS code, pickup date |",
        "| Consignee, seal number, signatures, delivery facts | Sampled in code from a seed. The tender email never named a consignee |",
        "| Pages | Drawn from the facts on one of four templates, assigned by company, then damaged. **No model writes anything** |",
        "| Scan damage | Applied in code after the page is drawn, token by token, with the changes recorded |",
        "| Defect labels and outcome | Planted or derived in code, so each is true by construction |",
        "",
        "## What a page is",
        "",
        "A list of tokens, each with text and a box, in the order an engine might emit them. It is **not an image**. "
        "No OCR confidence is provided: a simulated one would be a number the generator invented, correlated with "
        "the damage by construction, so the reader has to earn its own.",
        "",
        f"The Bill of Lading carries {len(BOL_FIELDS)} fields and the Proof of Delivery {len(POD_FIELDS)}.",
        "",
        "## Scan damage",
        "",
        "| Level | Share of pages (configured) | Value tokens damaged (configured) | Value tokens damaged (observed) | Fields damaged (observed) |",
        "|---|---|---|---|---|",
    ]
    for k in range(4):
        row = st["damage_by_level"][k]
        tok = row["damaged"] / max(1, row["tokens"])
        fld = row["fields_damaged"] / max(1, row["fields"])
        lines.append(f"| {k} | {DAMAGE_LEVEL_WEIGHTS[k]:.0%} | {DAMAGE_TOKEN_RATE[k]:.0%} | {tok:.1%} | {fld:.1%} |")
    lines += [
        "",
        "The observed rate is lower than the configured one because a token with no confusable character cannot be "
        "changed by a character swap. Report the observed number.",
        "",
        "## Paperwork defects",
        "",
        "| Defect | Configured rate | Loads carrying it |",
        "|---|---|---|",
    ]
    for d, rate in PAPER_DEFECTS.items():
        lines.append(f"| `{d}` | {rate:.2f} | {st['planted_defects'].get(d, 0)} |")
    lines += [
        "",
        "## Templates",
        "",
        "Pages per template: " + ", ".join(f"{k}: {v}" for k, v in st["templates"].items()) + ". "
        "Templates are assigned by company, so a shipper's forms look alike, and the spread follows how often each "
        "company appears: it is not even.",
        "",
        "## Failure modes this corpus does NOT contain",
        "",
        "- **No images.** Rotation, skew, stamps, handwriting, fax noise, coffee rings and photographed pages are all absent.",
        "- **The damage is modelled, not sampled from real scanners.** One fixed set of character confusions, token splits "
        "and dropped tokens. A real scanner fails in ways this does not.",
        "- No OCR confidence scores.",
        "- One page per document and one line item per load. No multi-page BOLs, no multi-stop, no continuation sheets.",
        f"- Only {N_TEMPLATES} templates. A fifth form will look different in ways these four do not.",
        "- Company names, seal numbers and signers are synthetic.",
        "- US truckload conventions only. No customs paperwork and no international forms.",
        "- The exceptions field takes only a few phrases. Real notes are free text.",
        "",
        "---",
        "",
        "Generated by [thilisynth](https://github.com/thili-ai/thilisynth) for the Learn Fast drill",
        "*Read the Freight Paperwork*.",
        "",
    ]
    return "\n".join(lines)


def deskcard_card(card: DeskCard) -> str:
    lines = [
        "# Corpus Card — `paperwork-rules-v1`",
        "",
        f"> The numbers Harborline's paperwork desk works to, as of {card.as_of}.",
        "",
        "## What it holds",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Weight tolerance | {card.weight_tolerance:.0%} of the booked weight |",
        f"| Pieces tolerance | {card.pieces_tolerance} |",
        f"| Accuracy floor for straight-through posting | {card.accuracy_floor:.1%} of posted fields correct |",
        f"| Cost of one human review | ${card.review_cost_usd:.2f} per document |",
        "",
        "## The consequence table",
        "",
        "The cost, in dollars, of posting a field wrong and nobody noticing:",
        "",
        "| Field | Tier | Cost of a wrong value |",
        "|---|---|---|",
    ]
    for key, cost in sorted(card.field_cost_usd.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{key}` | {card.tier[key]} | ${cost:,} |")
    lines += [
        "",
        "## These numbers are illustrative",
        "",
        "They were chosen to be plausible and to hang together: a wrong load reference costs more than a wrong weight, "
        "which costs more than a wrong commodity description. They are **not industry data and nothing was measured to "
        "produce them.** The drill teaches how a threshold follows from a cost. Change the costs and the thresholds "
        "should change with them.",
        "",
        "## Failure modes this corpus does NOT contain",
        "",
        "- One cost per field. No customer-specific penalties, no contract terms, no claim limits.",
        "- A review costs the same for every document and fixes every field on it.",
        "- Costs do not compound: two wrong fields cost the sum of their costs.",
        "",
        "---",
        "",
        "Generated by [thilisynth](https://github.com/thili-ai/thilisynth) for the Learn Fast drill",
        "*Read the Freight Paperwork*.",
        "",
    ]
    return "\n".join(lines)


def paperwork_truth_card(loads: Sequence[LoadPaperwork]) -> str:
    st = paperwork_stats(loads)
    lines = [
        "# Corpus Card — paperwork ground truth for `docs-v1`",
        "",
        f"> The correct outcome for {st['n']} loads: post the paperwork, or hold it for a reason.",
        "",
        "## How the truth is derived",
        "",
        "In code, from the facts on the documents and the booking: the pieces loaded and delivered, the weights, the "
        "references, the receiver, the seals, the signatures. It never comes from the scan damage and never from the "
        "learner's own policy, so a reader cannot mark itself right.",
        "",
        "## What it contains",
        "",
        f"- Post: **{st['post_share']:.1%}**. Hold: **{1 - st['post_share']:.1%}**.",
        "",
        "| Hold reason | Primary | Present at all |",
        "|---|---|---|",
    ]
    for r in PAPER_REASON_PRIORITY:
        lines.append(f"| `{r}` | {st['primary_reason_counts'].get(r, 0)} | {st['reason_counts'].get(r, 0)} |")
    lines += [
        "",
        "## Failure modes this corpus does NOT contain",
        "",
        "- Every hold reason is a planted defect. There is no ambiguous case where two honest readers would disagree.",
        "- A reading error is never a hold reason by itself: a load whose paperwork is clean but was scanned badly is a "
        "**post** in the truth, and the reader still has to be right about it.",
        "- No partial deliveries, no multi-stop, no re-consignment, no freight that is accepted despite an exception.",
        "",
        "---",
        "",
        "Generated by [thilisynth](https://github.com/thili-ai/thilisynth) for the Learn Fast drill",
        "*Read the Freight Paperwork*.",
        "",
    ]
    return "\n".join(lines)
