"""Write the CORPUS_CARD.md — the deliverable, modelled on a model card.

A corpus without a card is a pile of files. The card is what lets a grader
regenerate it, a teammate trust it, and you notice six months later that the
defect you assumed was in there never fired.

The section that carries the most weight is **the failure modes it does NOT
contain**, because that is the one nobody writes voluntarily.
"""
from __future__ import annotations

from typing import Any, Dict, Optional, Sequence

from .pipeline import Corpus


def corpus_card(
    corpus: Corpus,
    configured_defects: Dict[str, float],
    measurements: Dict[str, Any],
    sources: Sequence[str] = (),
    known_gaps: Sequence[str] = (),
    model: Optional[str] = None,
) -> str:
    observed = corpus.defect_rates
    never_fired = sorted(set(configured_defects) - set(observed))

    lines = [
        f"# Corpus Card — `{corpus.name}`",
        "",
        f"> {len(corpus.rows)} rows, generated by thilisynth from seed `{corpus.seed}`.",
        "",
        "## Reproduce",
        "",
        "```",
        f"seed      {corpus.seed}",
        f"renderer  {corpus.renderer}" + (f" ({model})" if model else ""),
        f"rows      {len(corpus.rows)}",
        "```",
        "",
        "Same seed, same renderer, same bytes.",
        "",
        "## Provenance",
        "",
        "| Layer | Origin |",
        "|---|---|",
        "| Ground-truth records | Sampled in code from the reference tables below. **Never model-generated.** |",
        f"| Surface text | Rendered by `{corpus.renderer}`" + (f" (`{model}`)" if model else "") + " |",
        "| Defect flags | Applied mechanically in code after verification |",
        "",
    ]

    if sources:
        lines += ["**Reference tables:**", ""] + [f"- {s}" for s in sources] + [""]

    lines += [
        "## Verification",
        "",
        f"- Renders rejected for contradicting their record: **{corpus.reject_rate:.2%}** "
        f"({len(corpus.rejected)} rows)",
        "",
        "Every render was diffed against its source record before any defect was applied.",
        "Rows whose every attempt contradicted the record were dropped, not kept.",
        "",
        "## Defects present",
        "",
        "| Defect | Configured | Observed |",
        "|---|---|---|",
    ]
    for name in sorted(configured_defects):
        lines.append(f"| `{name}` | {configured_defects[name]:.2f} | {observed.get(name, 0.0):.4f} |")

    lines += ["", "## Failure modes this corpus does NOT contain", ""]
    if never_fired:
        lines += [
            "**Configured but never fired — the corpus does not contain these, whatever the config says:**",
            "",
        ] + [f"- `{d}`" for d in never_fired] + [""]
    for gap in known_gaps:
        lines.append(f"- {gap}")
    if not never_fired and not known_gaps:
        lines.append("- *(none declared — this is almost certainly wrong; fill it in)*")

    lines += ["", "## Measurements", "", "| Metric | Value |", "|---|---|"]
    for k, v in measurements.items():
        lines.append(f"| `{k}` | {v} |")

    lines += [
        "",
        "---",
        "",
        "Generated by [thilisynth](https://github.com/thili-ai/thilisynth) for the",
        "Learn Fast drill *Generate Your Own Industry Dataset*.",
        "",
    ]
    return "\n".join(lines)
